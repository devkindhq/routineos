// Cells list the names they cover in data-cell, like the other showcase pages. Hooks and icons are demo panels.
class CellBoundary extends Component {
  constructor(props) { super(props); this.state = { err: null }; }
  static getDerivedStateFromError(err) { return { err }; }
  render() {
    if (this.state.err) return <Text c="red" data-cell-failed={this.props.name}>FAILED {this.props.name}: {String(this.state.err.message)}</Text>;
    return this.props.children;
  }
}
function Cell({ name, children }) {
  return (
    <Paper withBorder p="xs" data-cell={name}>
      <Text size="xs" ff="monospace" c="dimmed" mb={6}>{name}</Text>
      <CellBoundary name={name}>{children}</CellBoundary>
    </Paper>
  );
}
function Tile({ name, Icon }) {
  return (
    <div data-cell={name} style={{ display: "flex", flexDirection: "column", alignItems: "center", gap: 2, padding: 4 }}>
      <CellBoundary name={name}><Icon size={20} /></CellBoundary>
      <Text size="10px" c="dimmed" ta="center" style={{ wordBreak: "break-all" }}>{name.replace(/^Icon/, "")}</Text>
    </div>
  );
}

